def build_report(
    store: Store,
    url: str,
    *,
    settings: config.Settings = config.SETTINGS,
    emit: Emit | None = None,
) -> ReportResponse:
    emit = emit or (lambda _message: None)
    root = config.REPORT_ROOT
    try:
        store.read(config.SCAN_KEY)
    except Exception:
        storage_available = False
    else:
        storage_available = True

    clear_message = ""
    if wants_clear(url):
        try:
            scan_cleared = bool(store.write("{}", config.SCAN_KEY))
            test_cleared = bool(store.write("{}", config.TEST_KEY))
            clear_message = (
                "本工具的两份本地记录已清空。"
                if scan_cleared and test_cleared
                else "本地记录清空未完成。"
            )
        except Exception:
            clear_message = "本地存储接口暂未就绪。"

    def load(key: str) -> dict:
        return load_json(store, key) if storage_available else {}

    scan_raw = load(config.SCAN_KEY)
    test_raw = load(config.TEST_KEY)

    recorded_target = _sku(test_raw.get("target"))
    if not recorded_target and LEGACY_VERSION_RE.fullmatch(_text(test_raw.get("version"), 32)):
        recorded_target = config.LEGACY_TARGET

    matched_from = _rows(test_raw.get("matchedFrom"), False, recorded_target)
    if not recorded_target:
        for row in matched_from:
            if row["id"].startswith(config.SOURCE_PREFIX) and row["to"]:
                recorded_target = row["to"]
                break

    stored_annual = test_raw.get("annualHitCount")
    if isinstance(stored_annual, (int, float)) and not isinstance(stored_annual, bool):
        annual_hit_count = prior_count(stored_annual)
    else:
        annual_hit_count = sum(
            row["count"]
            for row in matched_from
            if row["id"].startswith(config.SOURCE_PREFIX)
        )

    stored_origin = _text(test_raw.get("targetOrigin"), 32)
    if recorded_target and stored_origin in ("user-specified", "pattern-derived", "legacy"):
        target_origin = stored_origin
    elif recorded_target in (settings.target, config.DEFAULT_TARGET):
        # Records written before --target existed still carry the built-in one.
        target_origin = config.TARGET_ORIGIN
    elif recorded_target == config.LEGACY_TARGET:
        target_origin = "legacy"
    else:
        target_origin = ""

    report = {
        "schemaVersion": config.SCHEMA_VERSION,
        "reportVersion": config.REPORT_VERSION,
        "configuredTarget": settings.target,
        "storageAvailable": storage_available,
        "scan": {
            "version": _text(scan_raw.get("version"), 32),
            "updatedAt": _text(scan_raw.get("updatedAt"), 32),
            "scannedResponses": prior_count(scan_raw.get("scannedResponses")),
            "matchedResponses": prior_count(scan_raw.get("matchedResponses")),
            "nonTextResponses": prior_count(scan_raw.get("nonTextResponses")),
            "recentResponses": _recent(scan_raw.get("recentResponses")),
            "truncated": scan_raw.get("truncated") is True,
            "limit": config.SCAN_LIMIT,
            "skus": _rows(scan_raw.get("skus"), True, ""),
        },
        "test": {
            "version": _text(test_raw.get("version"), 32),
            "updatedAt": _text(test_raw.get("updatedAt"), 32),
            "sourcePrefix": config.SOURCE_PREFIX,
            "target": recorded_target,
            "targetOrigin": target_origin,
            "status": _text(test_raw.get("status"), 32),
            "hitCount": prior_count(test_raw.get("hitCount")),
            "annualHitCount": annual_hit_count,
            "matchedFrom": matched_from,
        },
    }

    export_json = wants_json(url)
    emit(
        f"[g1-sku-report] {config.REPORT_VERSION} "
        f"{'json' if export_json else 'html'}"
        f" storage={'ready' if storage_available else 'unavailable'}"
        f" candidates={len(report['scan']['skus'])}"
    )

    headers = {
        "Content-Type": "text/html; charset=utf-8",
        "Cache-Control": "no-store",
        "X-G1-Report-Version": config.REPORT_VERSION,
        "X-Content-Type-Options": "nosniff",
        "Content-Security-Policy": (
            "default-src 'none'; style-src 'unsafe-inline'; base-uri 'none'; "
            "frame-ancestors 'none'"
        ),
    }
    if export_json:
        headers["Content-Type"] = "application/json; charset=utf-8"
        headers["Content-Disposition"] = 'attachment; filename="g1-sku-report.json"'
        return ReportResponse(200, headers, json.dumps(report, indent=2, ensure_ascii=False))

    return ReportResponse(200, headers, _html(report, clear_message, storage_available, root))


def _html(report: dict, clear_message: str, storage_available: bool, root: str) -> str:
    scan = report["scan"]
    test = report["test"]
    latest = scan["recentResponses"][-1] if scan["recentResponses"] else None
    if scan["version"] == config.COLLECTOR_VERSION:
        scan_version_status = "记录来自本版采集脚本；按响应时间与计数判断是否产生了新记录。"
    elif scan["version"]:
        scan_version_status = "旧采集记录；尚未保存本版采集响应记录。"
    else:
        scan_version_status = "尚未保存本版采集响应记录。"

    status = TEST_STATUSES.get(test["status"], "暂无测试执行记录")
    if test["version"] == "pro-annual-test-v1" and test["status"] == "no-match":
        status = "旧 v1 记录：本次响应未命中 iOS 2TB 前缀"

    parts = [
        "<!doctype html><html lang=zh-CN><meta charset=utf-8>",
        "<meta name=viewport content=\"width=device-width,initial-scale=1\">"
        "<title>Google One SKU 本地报告</title>",
        _STYLE,
        "<h1>Google One SKU 本地报告</h1>",
        f"<p class=badge>G1 ACQ 旁路已接管 · {config.REPORT_VERSION}</p>",
        "<nav class=actions aria-label=报告操作>"
        f"<form method=get action=\"{root}\">"
        "<button type=submit name=format value=json>导出 JSON</button></form>"
        f"<a href=\"{root}\">刷新报告</a></nav>",
        "<p class=note>此页由当前设备的 G1 ACQ 旁路服务生成；地址栏沿用 one.google.com，"
        "采集记录保存在旁路服务所在主机。</p>",
        "<p class=note>保持一个 G1 ACQ 服务开启即可：先采集原始响应中的编号，再执行三档改写。</p>",
        f"<p>{_escape(clear_message)}</p>" if clear_message else "",
        "" if storage_available else "<p>本地存储接口暂未就绪；此页尚未读取到采集记录。</p>",
        "<section><h2>采集运行记录</h2>",
        f"<p>实际采集脚本：<code>{_escape(scan['version'] or '暂无记录')}</code><br>"
        f"{scan_version_status}</p>",
        f"<p>已扫描文本响应：{scan['scannedResponses']}；"
        f"已记录非文本响应：{scan['nonTextResponses']}；"
        f"含商品编号的响应：{scan['matchedResponses']}；"
        f"累计编号：{len(scan['skus'])}</p>",
        f"<p>最近保存时间（UTC）：{_escape(scan['updatedAt'] or '暂无')}</p>",
        (
            f"<p><strong>最近一条：{SCAN_STATUSES[latest['status']]}</strong><br>"
            f"识别 {latest['candidateCount']} 个不同编号，新增录入 {latest['addedCount']} 个，"
            f"容量外 {latest['omittedCount']} 个。</p>"
            if latest
            else ""
        ),
        "<p class=note>累计清单按编号去重；收到相同编号会更新次数，清单条数保持不变。"
        "先记录计数和时间，重新打开 Google App 方案页，再刷新本报告对照。</p>",
        "<h3>最近 10 次响应</h3>",
        _recent_table(scan["recentResponses"]),
        "<p class=note>计数增加且显示重复编号，表示已收到响应；时间和计数保持原值，"
        "表示尚无新的匹配响应记录，可核对页面缓存、G1 ACQ 服务开关、Clash 分流规则、"
        "受信任的根证书与旁路服务日志中的 saved=no。路径仅保存分类。</p></section>",
        "<section><h2>最近一次三档映射</h2>",
        f"<p>当前配置的 2TB 候选目标：<code>{_escape(report['configuredTarget'])}</code></p>",
        "<p class=note>本版按指定 12months_ip_90p 编号测试，完整目标以 _ip_90p 结尾；"
        "实际商品、价格与扣款周期查看 App Store 购买面板。</p>",
        f"<p>版本：{_escape(test['version'] or '暂无')}<br>状态：{_escape(status)}；"
        f"总替换次数：{test['hitCount']}；其中 2TB：{test['annualHitCount']}</p>",
        f"<p>2TB 源前缀：<code>g1.ios.2tb.</code><br>"
        f"该次记录的 2TB 目标：<code>{_escape(test['target'] or '暂无记录')}</code><br>"
        "20TB / 30TB 沿用旧优惠映射与 75p 回退；各档实际目标见下表。<br>"
        f"执行时间（UTC）：{_escape(test['updatedAt'] or '暂无')}</p>",
        "<p class=note>这里记录的是脚本执行结果；商品是否被 App Store 识别、价格和周期"
        "需查看购买面板。</p>",
        _table(test["matchedFrom"], False),
        "</section>",
        "<section><h2>浏览页面时采集到的候选 SKU</h2>",
        f"<p>累计编号：{len(scan['skus'])}；同一编号合并计数，每次响应的新增与重复情况"
        "见上方采集运行记录。</p>",
        "<p class=note>编号在改写前从原始响应中提取，并非商店的完整商品目录；"
        "服务生成的替换目标不会自动加入这份清单。</p>",
        "<p>记录已达到 300 个上限；清空后可重新采集目标页面。</p>"
        if scan["truncated"]
        else "",
        _table(scan["skus"], True),
        f"<p>更新时间（UTC）：{_escape(scan['updatedAt'] or '暂无')}</p></section>",
        f"<form method=get action=\"{root}\">"
        "<button name=clear value=1>清空本工具的采集与测试记录</button></form>",
        "<p class=note>浏览方案后刷新本页查看记录；不要把同一个命令再接到其它改写副本上，"
        "避免重复记录。</p></html>",
    ]
    return "".join(parts)
