"""Local report served at ``https://one.google.com/g1-sku-report``.

The page is generated by the sidecar, never by Google.  It exposes only
whitelisted fields: no cookies, headers, bodies, query strings or full URLs.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from typing import Any, Callable

from . import config
from .collector import prior_count
from .store import Store, load_json
from .urls import ROUTES, wants_clear, wants_json

Emit = Callable[[str], None]

SKU_RE = re.compile(r"^g1\.[A-Za-z0-9._-]{1,160}$")
ID_RE = re.compile(r"^(?:g1\.|com\.google\.one\.)[A-Za-z0-9._-]{1,160}$")
# Versions whose 2TB records predate the ``target`` field.
LEGACY_VERSION_RE = re.compile(r"^(?:pro-annual-test-v[12]|g1-acq-v7(?:\.0|\.1)?)$")
# Same shape the collector writes; [0-9] because JavaScript's \d is ASCII-only.
_AT_RE = re.compile(r"[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(?:\.[0-9]{1,3})?Z")

SCAN_STATUSES = {
    "new-skus": "发现并录入新编号",
    "known-skus": "收到响应，编号与已有记录重复",
    "no-skus": "收到文本响应，本次没有商品编号",
    "limit-reached": "收到新编号，已达采集容量上限",
    "non-text": "收到响应，正文不是可扫描文本",
}

TEST_STATUSES = {
    "rewritten": "已执行字符串替换",
    "no-match": "本次响应未命中三档映射中的源商品",
    "non-text": "本次响应没有可处理的文本正文",
}


@dataclass
class ReportResponse:
    status: int
    headers: dict[str, str]
    body: str


def _text(value: Any, length: int = 180) -> str:
    return value[:length] if isinstance(value, str) else ""


def _sku(value: Any) -> str:
    return value if isinstance(value, str) and SKU_RE.fullmatch(value) else ""


def _rows(value: Any, with_time: bool, default_target: str) -> list[dict]:
    if not isinstance(value, list):
        return []
    out = []
    for row in value[:300]:
        if not isinstance(row, dict):
            continue
        row_id = row.get("id")
        if not isinstance(row_id, str) or not ID_RE.fullmatch(row_id):
            continue
        item = {"id": row_id, "count": prior_count(row.get("count"))}
        if with_time:
            item["lastSeen"] = _text(row.get("lastSeen"), 32)
        else:
            # Old v1 records have no ``to``; fall back to their 2TB target.
            is_two_tb = row_id.startswith(config.SOURCE_PREFIX)
            item["to"] = _sku(row.get("to")) or (
                (default_target or "") if is_two_tb else ""
            )
            item["fallback"] = row.get("fallback") is True
        out.append(item)
    out.sort(key=lambda item: item["id"])
    return out


def _recent(value: Any) -> list[dict]:
    if not isinstance(value, list):
        return []
    out = []
    for event in value[-config.RECENT_LIMIT :]:
        if not isinstance(event, dict):
            continue
        at = event.get("at")
        body_type = event.get("bodyType")
        status = event.get("status")
        if not isinstance(at, str) or not _AT_RE.fullmatch(at):
            continue
        if body_type not in ("text", "non-text"):
            continue
        # A stored status may be any JSON type; only a known string counts.
        if not isinstance(status, str) or status not in SCAN_STATUSES:
            continue
        path = event.get("path")
        out.append(
            {
                "at": at,
                "path": path if path in ROUTES else "[其他 one.google.com 路径]",
                "bodyType": body_type,
                "status": status,
                "candidateCount": prior_count(event.get("candidateCount")),
                "addedCount": prior_count(event.get("addedCount")),
                "omittedCount": prior_count(event.get("omittedCount")),
            }
        )
    return out


def _escape(value: Any) -> str:
    return (
        str(value)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
        .replace("'", "&#39;")
    )


def _table(items: list[dict], with_time: bool) -> str:
    if not items:
        return "<p>暂无记录。</p>"
    head = (
        "<div class=scroll><table><thead><tr><th>完整商品编号</th><th>次数</th>"
        + ("<th>最近发现时间（UTC）</th>" if with_time else "<th>实际目标 SKU</th><th>备用档</th>")
        + "</tr></thead><tbody>"
    )
    cells = []
    for row in items:
        if with_time:
            tail = f"<td>{_escape(row['lastSeen'])}</td>"
        else:
            tail = (
                f"<td><code>{_escape(row['to'] or '未记录')}</code></td>"
                f"<td>{'75p' if row['fallback'] else '否'}</td>"
            )
        cells.append(
            f"<tr><td><code>{_escape(row['id'])}</code></td>"
            f"<td>{row['count']}</td>{tail}</tr>"
        )
    return head + "".join(cells) + "</tbody></table></div>"


def _recent_table(events: list[dict]) -> str:
    if not events:
        return "<p>尚无逐次响应记录；旧版采集数据没有这项诊断。</p>"
    head = (
        "<div class=scroll><table><thead><tr><th>时间（UTC）</th><th>路径分类</th>"
        "<th>本次结果</th><th>识别编号</th><th>新增录入</th><th>容量外编号</th>"
        "</tr></thead><tbody>"
    )
    cells = [
        f"<tr><td>{_escape(event['at'])}</td><td>{_escape(event['path'])}</td>"
        f"<td>{SCAN_STATUSES[event['status']]}</td><td>{event['candidateCount']}</td>"
        f"<td>{event['addedCount']}</td><td>{event['omittedCount']}</td></tr>"
        for event in reversed(events)
    ]
    return head + "".join(cells) + "</tbody></table></div>"


